import { DIALOG_DATA, DialogRef } from '@angular/cdk/dialog';
import { Component, inject, signal, type Signal } from '@angular/core';
import { FormsModule } from '@angular/forms';
import type { AppManifest, ServerApp, SupplyView } from '@orbot/shared';
import { Api } from '../../core/api';
import { toUserError, type UserFacingError } from '../../core/api-error';
import { Toasts } from '../../ui/toast';

export interface InstallAppData {
  serverId: string;
  serverName: string;
  manifest: AppManifest;
  /** Reinstalling: start from the settings it has now. */
  current: ServerApp | null;
  credentials: Signal<string[]>;
}

/** Install (or reinstall) an app from deploy/apps, with the settings its manifest declares. */
@Component({
  selector: 'orb-install-app-dialog',
  imports: [FormsModule],
  template: `
    @let m = data.manifest;
    <form class="form" (ngSubmit)="submit()">
      <h2>{{ data.current ? 'Reinstall' : 'Install' }} {{ m.name }} on {{ data.serverName }}</h2>
      <p class="hint">{{ m.summary }}</p>
      @if (m.requires.length) {
        <p class="hint">Needs: {{ m.requires.join('; ') }}.</p>
      }
      @for (s of m.settings; track s.key) {
        @if (s.type === 'boolean') {
          <label class="check"
            ><input type="checkbox" [name]="s.key" [(ngModel)]="values[s.key]" />
            {{ s.label }}</label
          >
        } @else {
          <label [for]="'set-' + s.key">{{ s.label }}</label>
          <input
            [id]="'set-' + s.key"
            [name]="s.key"
            class="input"
            [class.mono]="s.type === 'string'"
            [type]="s.type === 'string' ? 'text' : 'number'"
            [attr.min]="s.min ?? null"
            [attr.max]="s.max ?? null"
            [attr.step]="s.type === 'number' ? 'any' : null"
            [attr.aria-describedby]="s.help ? 'help-' + s.key : null"
            [(ngModel)]="values[s.key]"
          />
        }
        @if (s.help) {
          <p class="hint" [id]="'help-' + s.key">{{ s.help }}</p>
        }
      }
      @for (x of m.secrets; track x.key) {
        @if (x.generate) {
          <p class="hint">
            <strong>{{ x.label }}:</strong>
            {{ x.help ?? 'generated by ORBOT and kept in the secrets store.' }}
          </p>
        } @else {
          <label [for]="'sec-' + x.key"
            >{{ x.label }}
            @if (x.optional) {
              <span class="hint">(optional)</span>
            }
          </label>
          <select
            [id]="'sec-' + x.key"
            [name]="'sec-' + x.key"
            class="input"
            [(ngModel)]="secrets[x.key]"
          >
            <option [ngValue]="null">{{ x.optional ? 'None' : 'Choose a credential' }}</option>
            @for (c of data.credentials(); track c) {
              <option [ngValue]="c">{{ c }}</option>
            }
          </select>
          @if (x.help) {
            <p class="hint">{{ x.help }}</p>
          }
        }
      }
      <p class="hint">
        It runs on the server as root (passwordless sudo) and keeps going if ORBOT stops. You can
        follow its log on this page; every command is on the record.
      </p>
      @if (error(); as e) {
        <p role="alert" class="error">{{ e.message }} {{ e.action }}</p>
      }
      <div class="actions">
        <button type="button" class="btn btn--ghost" (click)="ref.close()">Cancel</button>
        <button type="submit" class="btn btn--primary" [disabled]="busy()">
          {{ data.current ? 'Reinstall' : 'Install' }} {{ m.name }}
        </button>
      </div>
    </form>
  `,
  styles: `
    .check {
      display: inline-flex;
      align-items: center;
      gap: var(--space-2);
      font-weight: var(--font-weight-regular);
    }
    .error {
      color: var(--tone-danger);
    }
  `,
})
export class InstallAppDialog {
  protected readonly data = inject<InstallAppData>(DIALOG_DATA);
  protected readonly ref = inject<DialogRef<SupplyView>>(DialogRef);
  private readonly api = inject(Api);
  private readonly toasts = inject(Toasts);
  protected readonly values: Record<string, string | number | boolean> = Object.fromEntries(
    this.data.manifest.settings.map((s) => [
      s.key,
      this.data.current?.settings[s.key] ?? s.default,
    ]),
  );
  protected readonly secrets: Record<string, string | null> = Object.fromEntries(
    this.data.manifest.secrets
      .filter((s) => !s.generate)
      .map((s) => [s.key, this.data.current?.credentials[s.key] ?? null]),
  );
  protected readonly busy = signal(false);
  protected readonly error = signal<UserFacingError | null>(null);

  protected async submit(): Promise<void> {
    this.busy.set(true);
    this.error.set(null);
    const m = this.data.manifest;
    try {
      const settings = Object.fromEntries(
        m.settings.map((s) => {
          const v = this.values[s.key] ?? s.default;
          return [s.key, s.type === 'integer' || s.type === 'number' ? Number(v) : v];
        }),
      );
      const s = await this.api.installApp(this.data.serverId, {
        app: m.id,
        settings,
        credentials: this.secrets,
      });
      this.toasts.show({
        tone: 'success',
        message: `Installing ${m.name} on ${this.data.serverName}.`,
        detail: 'It runs on the server; follow its log here.',
      });
      this.ref.close(s);
    } catch (err) {
      this.error.set(toUserError(err));
    } finally {
      this.busy.set(false);
    }
  }
}
