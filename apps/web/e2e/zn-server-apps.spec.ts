import { expect, test } from '@playwright/test';
import { expectAccessible, setTheme } from './axe';

/** A server's page: what it is, the bot workspace, and installing an app from deploy/apps. */
test('a server page shows the GPU, offers the bot workspace, and installs vLLM (an unreachable server fails with why)', async ({
  page,
}) => {
  await page.goto('/supply?section=environments');
  const card = page
    .getByRole('list', { name: 'Servers & environments' })
    .getByRole('listitem')
    .filter({ hasText: 'gpu1' });
  await expect(card).toContainText('NVIDIA GeForce RTX 3090');
  await expect(card).toContainText('set up the bot workspace to keep them apart');
  await card.getByRole('link', { name: 'gpu1' }).click();

  await expect(page.getByRole('heading', { level: 1, name: 'gpu1' })).toBeVisible();
  await expect(page).toHaveURL(/\/supply\/servers\/[0-9a-f-]{36}$/);
  const what = page.getByRole('region', { name: 'What it is' });
  await expect(what).toContainText('Ubuntu 24.04.1 LTS');
  await expect(what).toContainText('NVIDIA GeForce RTX 3090, 24576 MiB');
  const ws = page.getByRole('region', { name: 'Bot workspace' });
  await expect(ws.getByRole('button', { name: 'Set up bot workspace' })).toBeVisible();
  const catalog = page.getByRole('list', { name: 'Apps that can be installed' });
  await expect(catalog).toContainText('vLLM');
  await expectAccessible(page, 'server page (dark)');

  await catalog.getByRole('button', { name: 'Install vLLM…' }).click();
  const dialog = page.getByRole('dialog', { name: 'Install vLLM' });
  await expect(dialog.getByLabel('Model', { exact: true })).toHaveValue('Qwen/Qwen3-14B-AWQ');
  await expect(dialog.getByLabel('Port')).toHaveValue('8000');
  await expect(dialog).toContainText('Generated by ORBOT and kept in the secrets store');
  await expect(dialog.getByLabel(/Hugging Face token/).locator('option:checked')).toHaveText(
    'None',
  );
  await expectAccessible(page, 'install vLLM dialog');
  await dialog.getByLabel('Port').fill('8001');
  await dialog.getByRole('button', { name: 'Install vLLM' }).click();
  await expect(
    page.getByRole('status').filter({ hasText: 'Installing vLLM on gpu1.' }),
  ).toBeVisible();

  const installed = page.getByRole('list', { name: 'Installed apps' });
  await expect(installed).toContainText('Failed', { timeout: 20_000 });
  await expect(installed).toContainText('could not start');
  await expect(installed).toContainText('check it is on and reachable');
  await expect(installed).toContainText('8001');
  await expect(
    installed.getByRole('button', { name: 'Change settings / reinstall' }),
  ).toBeVisible();
  await expect(page.getByRole('region', { name: 'Record' })).toContainText(
    'vLLM on gpu1: failed — could not start: ssh: Could not resolve hostname gpu1.invalid',
  );
  await setTheme(page, 'light');
  await expect(page.getByRole('list', { name: 'Installed apps' })).toContainText('Failed');
  await expectAccessible(page, 'server page (light)');
  await setTheme(page, 'dark');

  // Its API key is a credential in the depot, by name; Models waits for a working install.
  await page.goto('/supply?section=credentials');
  await expect(page.getByRole('list', { name: 'Credentials' })).toContainText(
    'gpu1.vllm.vllm_api_key',
  );
  await page.goto('/supply?section=models');
  await expect(page.getByText('No models yet')).toBeVisible();
  await expectAccessible(page, 'models (empty)');
});

test('edit a server: the form starts from what it is; a login that does not work is refused', async ({
  page,
}) => {
  await page.goto('/supply?section=environments');
  const card = page
    .getByRole('list', { name: 'Servers & environments' })
    .getByRole('listitem')
    .filter({ hasText: 'gpu1' });
  await card.getByRole('button', { name: 'Edit' }).click();
  const dialog = page.getByRole('dialog', { name: 'Edit gpu1' });
  await expect(dialog.getByRole('heading', { name: 'Edit gpu1' })).toBeVisible();
  await expect(dialog.getByLabel('Host', { exact: true })).toHaveValue('gpu1.invalid');
  await expect(dialog.getByLabel('SSH key (credential)').locator('option:checked')).toHaveText(
    'gpu1-key',
  );
  await expect(dialog.getByLabel('User')).toHaveValue('admin');
  await expect(dialog.getByRole('radio', { name: /Dev server/ })).toBeChecked();
  await expect(
    dialog.getByRole('checkbox', { name: /reinstalled: pin its new host key/ }),
  ).not.toBeChecked();
  await expectAccessible(page, 'edit server');

  // A URL is saved as it is: nothing to log in to.
  await dialog.getByLabel(/URL/).fill('http://gpu1.lan:8080');
  await dialog.getByRole('button', { name: 'Save changes' }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Saved gpu1.' })).toBeVisible();
  await expect(card).toContainText('http://gpu1.lan:8080');

  // A new user is tested first; this server cannot be reached, so nothing changes.
  await card.getByRole('button', { name: 'Edit' }).click();
  await dialog.getByLabel('User').fill('ops');
  await dialog.getByRole('button', { name: 'Save changes' }).click();
  await expect(dialog.getByRole('alert')).toContainText('could not log in as ops@gpu1.invalid');
  await dialog.getByRole('button', { name: 'Cancel' }).click();
  await card.getByRole('link', { name: 'Apps & workspace' }).click();
  await expect(page.getByRole('heading', { level: 1, name: 'gpu1' })).toBeVisible();
  await expect(page.locator('header.page-header')).toContainText('admin@gpu1.invalid:22');
  await expect(page.getByRole('button', { name: 'Edit' })).toBeVisible();
});

test('a plain environment has Edit too, and its form can make it a server', async ({ page }) => {
  await page.goto('/supply?section=environments');
  const card = page
    .getByRole('list', { name: 'Servers & environments' })
    .getByRole('listitem')
    .filter({ hasText: 'production' })
    .filter({ hasNotText: 'gpu1' });
  await card.getByRole('button', { name: 'Edit' }).click();
  const dialog = page.getByRole('dialog', { name: /^Edit / });
  await expect(dialog.getByRole('radio', { name: /Production/ })).toBeChecked();
  const asServer = dialog.getByRole('checkbox', { name: /server bots log in to over SSH/ });
  await expect(asServer).not.toBeChecked();
  await expect(dialog.getByLabel('Host', { exact: true })).toHaveCount(0);
  await asServer.check();
  await expect(dialog.getByLabel('Host', { exact: true })).toBeVisible();
  await expect(dialog.getByRole('button', { name: 'Save changes' })).toBeDisabled();
  await expectAccessible(page, 'edit a plain environment');
  await dialog.getByRole('button', { name: 'Cancel' }).click();
});
